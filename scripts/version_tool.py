#!/usr/bin/env python3
"""Single-source version management for ModEdit.

`Version.json` is the source of truth. This tool mirrors it into:

  * `Sources/ModEditCore/Version.swift`
  * `Sources/ModEditApp/Resources/Info.plist`
  * `iPad/Info.plist`
  * the README version marker

It also owns release tagging and the tag/version consistency check. The shell
entry point is `scripts/version.sh`; this file exists so JSON, plist and UTF-8
handling stay in one place.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION_JSON = ROOT / "Version.json"
SWIFT_VERSION = ROOT / "Sources/ModEditCore/Version.swift"
APP_PLIST = ROOT / "Sources/ModEditApp/Resources/Info.plist"
IPAD_PLIST = ROOT / "iPad/Info.plist"
README = ROOT / "README.md"

SEMVER = re.compile(r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
VERSION_MARKER = re.compile(r"<!-- VERSION -->.*?<!-- /VERSION -->", re.DOTALL)
CHANNELS = {"development", "beta", "release"}


def derive_build(marketing: str) -> int:
    major, minor, patch = (int(part) for part in marketing.split("."))
    if minor > 99 or patch > 99:
        fail(
            "minor and patch must be below 100 so the derived build number "
            "stays monotonic; see Docs/Versioning.md"
        )
    return major * 10000 + minor * 100 + patch

SWIFT_TEMPLATE = r'''// This file is generated by scripts/version.sh from Version.json.
// Do not edit it directly; run `scripts/version.sh sync` after changing Version.json.

/// Version information shared by the app, the CLI, and packaging scripts.
public enum ModEditVersion {
    /// Marketing version, matching the git tag (for example `0.41.0`).
    public static let marketing = "@MARKETING@"
    /// Monotonically increasing bundle build number.
    public static let build = @BUILD@
    /// Release channel: development, beta, or release.
    public static let channel = "@CHANNEL@"

    /// A compact display string for About panels and CLI output.
    public static var display: String { "\(marketing) (build \(build))" }
}
'''


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def load_version() -> dict:
    if not VERSION_JSON.exists():
        fail(f"{VERSION_JSON} is missing")
    try:
        data = json.loads(VERSION_JSON.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        fail(f"{VERSION_JSON} is not valid JSON: {exc}")
    if not isinstance(data, dict):
        fail(f"{VERSION_JSON} must contain a JSON object")

    marketing = data.get("marketingVersion")
    build = data.get("buildNumber")
    channel = data.get("channel")

    if not isinstance(marketing, str) or not SEMVER.fullmatch(marketing):
        fail("marketingVersion must look like MAJOR.MINOR.PATCH")
    if not isinstance(build, int) or isinstance(build, bool) or build <= 0:
        fail("buildNumber must be a positive integer")
    if not isinstance(channel, str) or channel not in CHANNELS:
        fail(f"channel must be one of {sorted(CHANNELS)}")

    expected_build = derive_build(marketing)
    if build != expected_build:
        fail(
            f"buildNumber {build} does not match {marketing} "
            f"(expected {expected_build}; see Docs/Versioning.md)"
        )

    return {
        "marketingVersion": marketing,
        "buildNumber": build,
        "channel": channel,
    }


def write_version_json(version: dict) -> None:
    VERSION_JSON.write_text(
        json.dumps(version, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def swift_source(version: dict) -> str:
    return (
        SWIFT_TEMPLATE.replace("@MARKETING@", version["marketingVersion"])
        .replace("@BUILD@", str(version["buildNumber"]))
        .replace("@CHANNEL@", version["channel"])
    )


def version_marker(version: dict) -> str:
    return (
        f"<!-- VERSION -->{version['marketingVersion']} "
        f"(build {version['buildNumber']})<!-- /VERSION -->"
    )


def set_plist_value(text: str, key: str, value: str) -> str:
    pattern = re.compile(
        rf"(<key>{re.escape(key)}</key>\s*<string>)[^<]*(</string>)"
    )
    updated, count = pattern.subn(
        lambda match: f"{match.group(1)}{value}{match.group(2)}",
        text,
    )
    if count != 1:
        fail(f"expected exactly one {key} in a plist, found {count}")
    return updated


def get_plist_value(text: str, key: str) -> str | None:
    pattern = re.compile(
        rf"<key>{re.escape(key)}</key>\s*<string>([^<]*)</string>"
    )
    match = pattern.search(text)
    return match.group(1) if match else None


def expected_files(version: dict) -> dict[Path, str]:
    app_text = APP_PLIST.read_text(encoding="utf-8")
    ipad_text = IPAD_PLIST.read_text(encoding="utf-8")
    readme_text = README.read_text(encoding="utf-8")

    updated_app = set_plist_value(
        app_text, "CFBundleShortVersionString", version["marketingVersion"]
    )
    updated_app = set_plist_value(
        updated_app, "CFBundleVersion", str(version["buildNumber"])
    )
    updated_ipad = set_plist_value(
        ipad_text, "CFBundleShortVersionString", version["marketingVersion"]
    )
    updated_ipad = set_plist_value(
        updated_ipad, "CFBundleVersion", str(version["buildNumber"])
    )

    updated_readme, marker_count = VERSION_MARKER.subn(
        version_marker(version), readme_text, count=1
    )
    if marker_count != 1:
        fail("README.md is missing exactly one <!-- VERSION --> marker pair")

    return {
        SWIFT_VERSION: swift_source(version),
        APP_PLIST: updated_app,
        IPAD_PLIST: updated_ipad,
        README: updated_readme,
    }


def lint_plist(path: Path) -> None:
    result = subprocess.run(
        ["plutil", "-lint", str(path)],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        fail(f"{path} is not a valid plist:\n{result.stderr}{result.stdout}")


def check() -> int:
    version = load_version()
    expected = expected_files(version)
    problems: list[str] = []

    for path, content in expected.items():
        try:
            actual = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            problems.append(f"{path.relative_to(ROOT)} (missing)")
            continue
        if actual != content:
            problems.append(str(path.relative_to(ROOT)))

    if problems:
        print("Version metadata is out of sync:", file=sys.stderr)
        for path in problems:
            print(f"  - {path}", file=sys.stderr)
        print("\nRun scripts/version.sh sync and commit the result.", file=sys.stderr)
        return 1

    print(
        f"Version metadata is consistent: {version['marketingVersion']} "
        f"(build {version['buildNumber']}, {version['channel']})"
    )
    return 0


def sync() -> int:
    version = load_version()
    expected = expected_files(version)
    changed: list[Path] = []

    for path, content in expected.items():
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        if actual != content:
            path.write_text(content, encoding="utf-8")
            changed.append(path)
        if path.suffix == ".plist":
            lint_plist(path)

    if changed:
        print(
            f"Synced {version['marketingVersion']} "
            f"(build {version['buildNumber']}) to:"
        )
        for path in changed:
            print(f"  - {path.relative_to(ROOT)}")
    else:
        print(
            f"Already synced: {version['marketingVersion']} "
            f"(build {version['buildNumber']})"
        )
    return 0


def bump(kind: str) -> int:
    version = load_version()
    major, minor, patch = (int(part) for part in version["marketingVersion"].split("."))

    if kind == "major":
        major, minor, patch = major + 1, 0, 0
    elif kind == "minor":
        minor, patch = minor + 1, 0
    elif kind == "patch":
        patch += 1
    else:
        fail("bump expects one of: patch, minor, major")

    new_marketing = f"{major}.{minor}.{patch}"
    new_version = {
        "marketingVersion": new_marketing,
        "buildNumber": derive_build(new_marketing),
        "channel": version["channel"],
    }
    write_version_json(new_version)
    sync()
    print(
        f"Bumped to {new_version['marketingVersion']} "
        f"(build {new_version['buildNumber']})"
    )
    print("Next: commit the change, wait for CI, then run scripts/version.sh tag")
    return 0


def set_version(value: str) -> int:
    if not SEMVER.fullmatch(value):
        fail("version must look like MAJOR.MINOR.PATCH")
    version = load_version()
    new_version = {
        "marketingVersion": value,
        "buildNumber": derive_build(value),
        "channel": version["channel"],
    }
    write_version_json(new_version)
    sync()
    print(f"Set version to {value} (build {new_version['buildNumber']})")
    return 0


def working_tree_is_clean() -> bool:
    result = subprocess.run(
        ["git", "-C", str(ROOT), "status", "--porcelain"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        fail("could not inspect the git working tree")
    return result.stdout.strip() == ""


def verify_tag() -> int:
    version = load_version()

    if not working_tree_is_clean():
        fail("working tree is dirty; commit before verifying or creating a tag")

    result = subprocess.run(
        [
            "git",
            "-C",
            str(ROOT),
            "describe",
            "--tags",
            "--exact-match",
            "HEAD",
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        fail("HEAD is not tagged; create the release tag first")

    tag = result.stdout.strip()
    if tag != version["marketingVersion"]:
        fail(
            f"HEAD tag {tag!r} does not match Version.json "
            f"{version['marketingVersion']!r}"
        )

    print(f"Tag {tag} matches Version.json")
    return 0


def create_tag() -> int:
    version = load_version()
    name = version["marketingVersion"]

    if not working_tree_is_clean():
        fail("working tree is dirty; commit before creating a tag")
    if check() != 0:
        fail("version metadata is out of sync; run scripts/version.sh sync")

    existing = subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "-q", "--verify", f"refs/tags/{name}"],
        capture_output=True,
        text=True,
    )
    if existing.returncode == 0:
        fail(f"tag {name} already exists")

    subprocess.run(
        [
            "git",
            "-C",
            str(ROOT),
            "tag",
            "-a",
            name,
            "-m",
            f"ModEdit {name}",
        ],
        check=True,
    )
    print(f"Created annotated tag {name}")
    print(f"Next: git push origin {name}")
    print(
        "Then update Release/EcosystemVersions.json if this is a coordinated "
        "ecosystem release."
    )
    return 0


def show(*args: str) -> int:
    version = load_version()
    if not args:
        print(
            f"{version['marketingVersion']} "
            f"(build {version['buildNumber']}, {version['channel']})"
        )
    elif args[0] == "--marketing":
        print(version["marketingVersion"])
    elif args[0] == "--build":
        print(version["buildNumber"])
    elif args[0] == "--channel":
        print(version["channel"])
    elif args[0] == "--json":
        print(json.dumps(version, indent=2))
    else:
        fail("show accepts --marketing, --build, --channel, or --json")
    return 0


def main(argv: list[str]) -> int:
    if not argv or argv[0] == "show":
        return show(*argv[1:])
    command = argv[0]
    if command == "check":
        return check()
    if command == "sync":
        return sync()
    if command == "bump":
        if len(argv) != 2:
            fail("bump expects one of: patch, minor, major")
        return bump(argv[1])
    if command == "set":
        if len(argv) != 2:
            fail("set expects MAJOR.MINOR.PATCH")
        return set_version(argv[1])
    if command == "verify-tag":
        return verify_tag()
    if command == "tag":
        return create_tag()
    fail(f"unknown command {command!r}")
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
