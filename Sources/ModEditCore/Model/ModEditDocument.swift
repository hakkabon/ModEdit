import AppKit
import SwiftUI
import UniformTypeIdentifiers

/// The AppKit document shell.
///
/// SwiftUI's `ReferenceFileDocument` writes the file after `fileWrapper` returns
/// and offers no completion callback, so it cannot distinguish a successful save
/// from a failed disk write. `NSDocument` does: its `save(to:ofType:for:
/// completionHandler:)` completes after the safe-save machinery has finished.
/// That callback is the only place this app marks a generation as saved.
@objc(ModEditDocument)
@MainActor
final class ModEditDocument: NSDocument {

    /// The lock-protected text buffer. `nonisolated` so `NSDocument` can use it
    /// from the background thread it writes on.
    nonisolated let buffer = EditorDocument()

    /// Generated by `write` and consumed by the save completion handler.
    nonisolated private let pendingWrite = PendingWrite()

    override class var autosavesInPlace: Bool { true }

    override nonisolated class var readableTypes: [String] { allTypeIdentifiers }
    override nonisolated class var writableTypes: [String] { allTypeIdentifiers }

    private nonisolated static var allTypeIdentifiers: [String] {
        FormatRegistry.standard.readableContentTypes.map(\.identifier)
    }

    override init() {
        super.init()
        if fileType == nil {
            fileType = FormatRegistry.standard.fallback.contentTypes.first?.identifier
                ?? UTType.plainText.identifier
        }
    }

    // MARK: Window

    override func makeWindowControllers() {
        let model = EditorModel(document: buffer)
        model.onTextChange = { [weak self] in
            // This drives autosave, the window's edited dot and close prompts.
            self?.updateChangeCount(.changeDone)
        }
        model.onFormatChange = { [weak self] format in
            guard let self, let identifier = format.contentTypes.first?.identifier else { return }
            self.fileType = identifier
        }

        let controller = ModEditWindowController(model: model)
        addWindowController(controller)
        controller.synchronizeWindowTitleWithDocumentName()
    }

    // MARK: Reading

    override func read(from data: Data, ofType typeName: String) throws {
        let decoded = try TextIO.decode(data)
        buffer.load(decoded, format: contentFormat(for: typeName, fileExtension: nil))
    }

    override func read(from url: URL, ofType typeName: String) throws {
        let decoded = try TextIO.decode(Data(contentsOf: url))
        let fileExtension = url.pathExtension.isEmpty ? nil : url.pathExtension
        buffer.load(decoded, format: contentFormat(for: typeName, fileExtension: fileExtension))
    }

    // MARK: Writing

    /// Used by print/duplicate and by `NSDocument`'s default file-wrapper path.
    override func data(ofType typeName: String) throws -> Data {
        let snapshot = buffer.snapshot()
        // The snapshot is the expensive part; the rest may continue off-main.
        unblockUserInteraction()
        return try TextIO.encode(snapshot.text,
                                 as: snapshot.encoding,
                                 withUTF8BOM: snapshot.hasUTF8BOM)
    }

    override func write(to url: URL,
                        ofType typeName: String,
                        for saveOperation: NSDocument.SaveOperationType,
                        originalContentsURL absoluteOriginalContentsURL: URL?) throws {
        let snapshot = buffer.snapshot()
        unblockUserInteraction()

        let data = try TextIO.encode(snapshot.text,
                                     as: snapshot.encoding,
                                     withUTF8BOM: snapshot.hasUTF8BOM)
        // `NSDocument.writeSafely` also performs a safe replace; this keeps the
        // inner write atomic as well, so a crash cannot leave a partial file.
        try data.write(to: url, options: .atomic)

        // Only a completed inner write is a candidate. The save completion
        // handler is still the place that marks the generation saved, because
        // the outer safe-save can fail while moving the file into place.
        pendingWrite.record(snapshot.generation)
    }

    /// Saves via the `NSDocument` safe-save machinery and records success only
    /// after it completes without an error.
    override func save(to url: URL,
                       ofType typeName: String,
                       for saveOperation: NSDocument.SaveOperationType,
                       completionHandler: @escaping (Error?) -> Void) {
        let pending = pendingWrite
        let buffer = buffer
        // Only operations that make this file the document's saved contents
        // clear the edited state. Exporting a copy and autosaving an untitled
        // draft to the Autosave Information folder do not.
        let recordsSuccess: Bool
        switch saveOperation {
        case .saveOperation, .saveAsOperation,
             .autosaveInPlaceOperation, .autosaveAsOperation:
            recordsSuccess = true
        case .saveToOperation, .autosaveElsewhereOperation:
            recordsSuccess = false
        @unknown default:
            recordsSuccess = false
        }

        pending.begin()
        super.save(to: url, ofType: typeName, for: saveOperation) { error in
            let writtenGeneration = pending.finish()
            if error == nil, recordsSuccess, let writtenGeneration {
                buffer.recordSuccessfulWrite(generation: writtenGeneration)
            }
            completionHandler(error)
        }
    }

    override func canAsynchronouslyWrite(to url: URL,
                                         ofType typeName: String,
                                         for saveOperation: NSDocument.SaveOperationType) -> Bool {
        // The buffer is lock-protected and the snapshot is taken before this
        // returns; encoding and the disk write must not block typing.
        true
    }

    // MARK: Helpers

    private nonisolated func contentFormat(for typeName: String,
                                           fileExtension: String?) -> any DocumentFormat {
        if let fileExtension,
           let type = UTType(filenameExtension: fileExtension) {
            return FormatRegistry.standard.format(for: type)
        }
        if let type = UTType(typeName) {
            return FormatRegistry.standard.format(for: type)
        }
        return FormatRegistry.standard.fallback
    }
}

/// A small thread-safe hand-off from the background writer to the main-thread
/// save completion handler.
///
/// `NSDocument` serialises saves for a document, so one slot is enough. `begin`
/// prevents a direct `write` call that is not part of a save from leaving a
/// stale generation behind.
private final class PendingWrite: @unchecked Sendable {
    private let lock = NSLock()
    private var isActive = false
    private var generation: UInt64?

    func begin() {
        lock.withLock {
            isActive = true
            generation = nil
        }
    }

    func record(_ writtenGeneration: UInt64) {
        lock.withLock {
            guard isActive else { return }
            generation = writtenGeneration
        }
    }

    func finish() -> UInt64? {
        lock.withLock {
            let result = generation
            isActive = false
            generation = nil
            return result
        }
    }
}

/// The window controller for one document.
///
/// SwiftUI still draws the contents, but the window, toolbar and document are
/// AppKit's so that `NSDocument` can manage the edited state and saving.
@MainActor
final class ModEditWindowController: NSWindowController, NSToolbarDelegate {
    private static let previewItem = NSToolbarItem.Identifier("ModEdit.TogglePreview")

    let model: EditorModel

    init(model: EditorModel) {
        self.model = model

        let hosting = NSHostingController(rootView: EditorRootView(model: model))
        let window = NSWindow(contentViewController: hosting)
        window.styleMask = [.titled, .closable, .miniaturizable, .resizable]
        window.setContentSize(NSSize(width: 1_100, height: 720))
        window.contentMinSize = NSSize(width: 500, height: 300)
        window.tabbingMode = .preferred
        window.isReleasedWhenClosed = false
        window.setFrameAutosaveName("ModEditDocumentWindow")

        super.init(window: window)

        let toolbar = NSToolbar(identifier: "ModEdit.Toolbar")
        toolbar.delegate = self
        toolbar.displayMode = .iconOnly
        toolbar.allowsUserCustomization = false
        window.toolbar = toolbar
        window.toolbarStyle = .unified
    }

    required init?(coder: NSCoder) { fatalError("init(coder:) is not supported") }

    @objc private func togglePreview(_ sender: Any?) {
        model.showPreview.toggle()
    }

    func toolbarDefaultItemIdentifiers(_ toolbar: NSToolbar) -> [NSToolbarItem.Identifier] {
        [.flexibleSpace, Self.previewItem]
    }

    func toolbarAllowedItemIdentifiers(_ toolbar: NSToolbar) -> [NSToolbarItem.Identifier] {
        [.flexibleSpace, Self.previewItem]
    }

    func toolbar(_ toolbar: NSToolbar,
                 itemForItemIdentifier itemIdentifier: NSToolbarItem.Identifier,
                 willBeInsertedIntoToolbar flag: Bool) -> NSToolbarItem? {
        guard itemIdentifier == Self.previewItem else { return nil }
        let item = NSToolbarItem(itemIdentifier: itemIdentifier)
        item.label = "Preview"
        item.paletteLabel = "Preview"
        item.toolTip = "Show or hide the live preview"
        item.image = NSImage(systemSymbolName: "sidebar.right",
                             accessibilityDescription: "Preview")
        item.target = self
        item.action = #selector(togglePreview(_:))
        item.isBordered = true
        return item
    }

    func validateToolbarItem(_ item: NSToolbarItem) -> Bool {
        guard item.itemIdentifier == Self.previewItem else { return true }
        return model.format.makePreviewRenderer() != nil
    }
}
